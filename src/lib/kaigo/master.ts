/* ---------- flatUnits の各項目が要介護／要支援どちら向けか ----------
 * flatUnits は数値が直接入っているため、そのままだと要支援でも要介護でも
 * 同じ値を返してしまう。サービスごとの flatScope で振り分ける。
 *   'kaigo' = 要介護のみ（訪問介護・訪問看護の一部など。予防は総合事業）
 *   'yobo'  = 要支援のみ
 *   'both'  = どちらでも同じ単位数
 *   'auto'  = 項目名に「予防」が入っていれば要支援用、なければ要介護用
 */
export function 項目の対象(serviceKey: string, entryName?: string | null): 限度額対象範囲 {
  const def = サービス[serviceKey];
  const scope = def?.flatScope || "both";
  if (scope !== "auto") return scope;
  return /予防/.test(entryName || "") ? "yobo" : "kaigo";
}

