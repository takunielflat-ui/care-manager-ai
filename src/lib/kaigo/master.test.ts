const U = (s: string, a: string, b: string, d: string): number => {
  const table = (サービス[s].units ?? サービス[s].flatUnits) as 単位表;
  const cell = table[a][b] as 度別単位;
  return cell[d as keyof 度別単位] ?? 0;
};
const F = (s: string, a: string, b: string): number => {
  const table = サービス[s].flatUnits as 単位表;
  return table[a][b] as number;
};

