/** モードに応じたシステムプロンプトを組み立てる。 */
export function getFifthSheetSystemPrompt(mode: GenerationMode): string {
  const [outputFormat, volumeRules] =
    mode === "detailed"
      ? [DETAILED_OUTPUT_FORMAT, DETAILED_VOLUME_RULES]
      : [CONCISE_OUTPUT_FORMAT, CONCISE_VOLUME_RULES];

  return [
    ROLE,
    RECORD_CONTEXT,
    outputFormat,
    volumeRules,
    WRITING_PRINCIPLES,
    CARE_MANAGEMENT_PERSPECTIVE,
    PROHIBITED_EXPRESSIONS,
    PRIVACY_RULES,
  ].join("\n\n");
}

