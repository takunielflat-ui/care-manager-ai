-- =====================================================================
-- 既存の保存データから、利用者の実名（印刷名）を消す（1回だけ実行する）
-- ---------------------------------------------------------------------
-- 2026-11 以前の保存（tanni_plans.state）には、PDF用のお名前「印刷名」が
-- 入っている場合がある。新しい保存ではアプリ側・API側の両方で送らない／捨てる
-- ようにしたので、過去分だけこのSQLで取り除く。
--
-- ※ title（プラン名）は利用者が自由に入力した文字列のため、ここでは消せない。
--    実名が入っていないか、件数だけ確認したい場合は下の SELECT を使う
--    （中身は表示しない）。
-- =====================================================================

-- 1. 対象件数の確認（中身は見ない）
select count(*) as 印刷名ありの件数
from public.tanni_plans
where state ? '印刷名' and coalesce(state->>'印刷名', '') <> '';

-- 2. 取り除く
update public.tanni_plans
set state = state - '印刷名'
where state ? '印刷名';
